package sb.broker.bff.access;

/**
 * Закрывает ли метод отсутствие обязательного согласия.
 */
public enum ConsentPolicy {
    /** Справочники и передача факта согласия: метод доступен и без обязательного согласия. */
    IGNORE,
    /** Полисы, профили, отзыв согласия: без обязательного согласия метод отвечает {@code consents_required}. */
    ENFORCE
}
